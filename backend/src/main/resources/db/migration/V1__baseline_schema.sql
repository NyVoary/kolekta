-- ============================================================
-- KOLEKTA - Schéma initial
-- Tables des modules présents : référentiels, employés, accès, clients.
-- Les clés primaires sont des BIGINT auto-générées (identity), comme les entités JPA.
-- ============================================================

-- ------------------------------------------------------------
-- Référentiels
-- ------------------------------------------------------------

CREATE TABLE sexe (
    code     VARCHAR(1)  PRIMARY KEY,
    libelle  VARCHAR(20) NOT NULL UNIQUE
);

CREATE TABLE modepaiement (
    id_mode  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle  VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE roles (
    id_role  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle  VARCHAR(20) NOT NULL UNIQUE
);

-- ------------------------------------------------------------
-- Employés et accès
-- date_fin_embauche reste NULL tant que l'employé est en poste.
-- ------------------------------------------------------------

CREATE TABLE employes (
    id_employe        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom               VARCHAR(100)   NOT NULL,
    prenoms           VARCHAR(100)   NOT NULL,
    dtn               DATE           NOT NULL,
    sexe              VARCHAR(1)     REFERENCES sexe (code),
    email             VARCHAR(255),
    telephone         VARCHAR(20),
    adresse           VARCHAR(255),
    poste             VARCHAR(100),
    date_embauche     DATE           NOT NULL,
    date_fin_embauche DATE,
    salaire           NUMERIC(10, 2) NOT NULL,
    id_mode           BIGINT         NOT NULL REFERENCES modepaiement (id_mode),
    image             VARCHAR(100)
);

-- Séparé de employes : un profil RH n'est pas un identifiant de connexion
CREATE TABLE acces (
    id_acces        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_employe      BIGINT       NOT NULL REFERENCES employes (id_employe) ON DELETE CASCADE,
    nom_utilisateur VARCHAR(50)  NOT NULL UNIQUE,
    mot_de_passe    VARCHAR(255) NOT NULL,
    id_role         BIGINT       NOT NULL REFERENCES roles (id_role)
);

CREATE INDEX idx_acces_employe ON acces (id_employe);

-- ------------------------------------------------------------
-- Clients
-- ------------------------------------------------------------

CREATE TABLE clients (
    id_client          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom                VARCHAR(100) NOT NULL,
    prenoms            VARCHAR(100) NOT NULL,
    dtn                DATE         NOT NULL,
    sexe               VARCHAR(1)   REFERENCES sexe (code),
    email              VARCHAR(255) UNIQUE,
    telephone          VARCHAR(20)  NOT NULL,
    adresse            VARCHAR(255) NOT NULL,
    mdp                VARCHAR(255),
    image              VARCHAR(100),
    date_creation      DATE         DEFAULT CURRENT_DATE,
    estactif           BOOLEAN      NOT NULL DEFAULT TRUE,
    date_desactivation DATE
);
